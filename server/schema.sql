-- Esquema de DLCritic en PostgreSQL (Neon). Es idempotente: se puede correr las veces que haga falta.
-- Aplicarlo con: npm run db:migrate
--
-- Equivalencias con el esquema anterior de SQLite: los flags siguen siendo INTEGER 0/1, las listas y objetos
-- siguen guardados como texto JSON y las fechas como texto ISO, para que el código de la app no cambie.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  email TEXT,
  pin_hash TEXT NOT NULL,
  joined_at TEXT NOT NULL,
  favorite_game_id TEXT,
  wishlist TEXT NOT NULL DEFAULT '[]',
  activity_dates TEXT NOT NULL DEFAULT '[]',
  is_admin INTEGER NOT NULL DEFAULT 0,
  avatar_url TEXT,
  bio TEXT,
  social_links TEXT NOT NULL DEFAULT '{}'
);
-- Verificación en dos pasos (TOTP) de las cuentas admin. totp_secret queda guardada tal cual (como el hash de la contraseña: una copia de la base
-- o de los backups la incluye, así que hay que cuidarlos). totp_enabled pasa a 1 recién cuando se confirma un primer código. totp_last_step
-- es el último paso de 30 s ya usado (un código no se puede usar dos veces). totp_recovery es un arreglo JSON con los hashes de los códigos de recuperación sin usar.
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_secret TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_enabled INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_last_step BIGINT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_recovery TEXT NOT NULL DEFAULT '[]';
-- El juego favorito marcado como platinado (lo marca la persona a mano; se muestra en su panel de Juego favorito, junto a los logros).
-- Es del juego favorito: al cambiar de favorito el servidor lo vuelve a 0.
ALTER TABLE users ADD COLUMN IF NOT EXISTS favorite_platinum INTEGER NOT NULL DEFAULT 0;
-- Cuenta de Steam vinculada (SteamID64, de 17 dígitos; lo confirma Steam con OpenID, nunca vemos su contraseña). Un Steam solo puede estar en una cuenta.
-- steam_synced_at: la última vez que se trajeron las horas. library_public: la biblioteca se ve en el perfil público (encendido por defecto; se apaga en Ajustes).
-- steam_hours_public: las horas de Steam se ven en el perfil público (también encendido por defecto).
ALTER TABLE users ADD COLUMN IF NOT EXISTS steam_id TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS steam_synced_at TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS library_public INTEGER NOT NULL DEFAULT 1;
ALTER TABLE users ADD COLUMN IF NOT EXISTS steam_hours_public INTEGER NOT NULL DEFAULT 1;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_steam_id ON users(steam_id);
-- Correo confirmado: la fecha en que la persona abrió el enlace que le llegó (o en que Google lo confirmó). NULL = sin confirmar; cambiar el correo en Ajustes lo vuelve a NULL.
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TEXT;
-- Inicio de sesión con Google: google_sub es el identificador estable de su cuenta de Google (único). has_password es 0 en las cuentas creadas con Google (y en las que se
-- vincularon sin correo confirmado): su pin_hash es una clave al azar que nadie conoce, y para tener contraseña usan «¿Olvidaste tu contraseña?».
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_sub TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS has_password INTEGER NOT NULL DEFAULT 1;
-- Rol de suscriptor (1 = lo es): borde multicolor en la foto de perfil, GIFs como foto y las demás ventajas que se vayan sumando. Se da con npm run make-subscriber.
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_subscriber INTEGER NOT NULL DEFAULT 0;
-- Estilo del icono de rango de un suscriptor (se elige en Ajustes): invert, gold, multi o un color #rrggbb. NULL = el de por defecto (invert).
ALTER TABLE users ADD COLUMN IF NOT EXISTS rank_icon_style TEXT;
-- Moderación. suspended_at: cuenta suspendida por un admin (no puede entrar ni se ven sus sesiones); NULL = activa.
ALTER TABLE users ADD COLUMN IF NOT EXISTS suspended_at TEXT;
-- Foto de perfil animada (GIF) de un suscriptor: queda en avatar_pending_url hasta que un admin la aprueba (entonces pasa a avatar_url) o la rechaza.
-- avatar_review_status: 'pending' (en revisión) o 'rejected' (la última no se aprobó); NULL si no hay nada.
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_pending_url TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_review_status TEXT;
-- Bandeja de moderación: lo que el filtro de palabras marca y lo que reportan los usuarios.
-- kind: review | character_review | bio | list | user; target_id: id de la reseña o lista (en bio y user, el id de la persona); author_id: quien lo escribió.
-- source: auto (filtro) | report; tier: grave | revisar (auto) o el motivo del reporte; text: el texto ORIGINAL (antes de censurar).
-- resolution: ok | hidden | cleared | deleted | avatar_removed | suspended.
CREATE TABLE IF NOT EXISTS moderation_flags (
  id TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  target_id TEXT,
  author_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  reporter_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  source TEXT NOT NULL,
  tier TEXT,
  note TEXT,
  text TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  resolution TEXT,
  created_at TEXT NOT NULL,
  resolved_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_moderation_flags_status ON moderation_flags(status, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google_sub ON users(google_sub);
-- Enlaces para confirmar el correo: se guarda el hash del token (como en password_resets) y el correo al que se mandó, para que valga solo si sigue siendo el de la cuenta.
CREATE TABLE IF NOT EXISTS email_verifications (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_email_verifications_user ON email_verifications(user_id);
-- Código de 6 dígitos para eliminar una cuenta que no tiene contraseña (las creadas con Google): se guarda su hash (el código solo viaja en el correo), vence a los 15 minutos y
-- deja de valer tras 5 intentos fallidos. Hay uno por persona: pedir otro anula el anterior.
CREATE TABLE IF NOT EXISTS account_deletion_codes (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  code_hash TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0
);
-- Horas jugadas (en minutos) de cada persona en los juegos del catálogo que tiene en Steam; se actualizan en cada sincronización.
CREATE TABLE IF NOT EXISTS steam_playtime (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  game_id TEXT NOT NULL,
  minutes INTEGER NOT NULL,
  PRIMARY KEY (user_id, game_id)
);
-- Logros del juego (obtenidos y totales): solo se traen para el juego favorito. NULL = todavía no se trajeron; total 0 = el juego no tiene logros en Steam.
ALTER TABLE steam_playtime ADD COLUMN IF NOT EXISTS achievements_unlocked INTEGER;
ALTER TABLE steam_playtime ADD COLUMN IF NOT EXISTS achievements_total INTEGER;
-- Varias cuentas sin email siguen permitidas (NULL no choca con NULL en un índice único).
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users(email);
-- Los nombres de usuario no distinguen mayúsculas (la app los busca con lower()).
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_ci ON users(lower(username));

CREATE TABLE IF NOT EXISTS follows (
  follower_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  followed_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  PRIMARY KEY (follower_id, followed_id)
);
CREATE INDEX IF NOT EXISTS idx_follows_followed ON follows(followed_id);

CREATE TABLE IF NOT EXISTS game_lists (
  id TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  is_public INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_game_lists_user ON game_lists(user_id);

CREATE TABLE IF NOT EXISTS game_list_items (
  list_id TEXT NOT NULL REFERENCES game_lists(id) ON DELETE CASCADE,
  game_id TEXT NOT NULL,
  added_at TEXT NOT NULL,
  PRIMARY KEY (list_id, game_id)
);
CREATE INDEX IF NOT EXISTS idx_game_list_items_list ON game_list_items(list_id);

CREATE TABLE IF NOT EXISTS notifications (
  id TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  actor_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  game_id TEXT,
  read INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, created_at);

-- Enlaces de recuperación de contraseña: se guarda el hash del token (el token solo viaja en el correo), vence a la hora y sirve una vez.
CREATE TABLE IF NOT EXISTS password_resets (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_password_resets_user ON password_resets(user_id);

CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS games (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  genre TEXT NOT NULL,
  genres TEXT NOT NULL DEFAULT '[]',
  platforms TEXT NOT NULL DEFAULT '[]',
  added_by TEXT,
  created_at TEXT NOT NULL,
  cover_url TEXT,
  card_cover_url TEXT,
  description TEXT,
  developer TEXT,
  publisher TEXT,
  release_year INTEGER,
  game_mode TEXT,
  store_links TEXT NOT NULL DEFAULT '{}',
  hidden INTEGER NOT NULL DEFAULT 0,
  is_new_release INTEGER NOT NULL DEFAULT 0,
  new_release_date TEXT,
  builtin INTEGER NOT NULL DEFAULT 0
);
-- Las búsquedas por título (portadas) comparan en minúsculas.
CREATE INDEX IF NOT EXISTS idx_games_title_lower ON games(lower(title));
-- Id del juego en Steam (el número de store.steampowered.com/app/<id>): con él se cruzan los juegos de la cuenta de Steam con el catálogo. Los juegos fuera de Steam quedan en NULL.
ALTER TABLE games ADD COLUMN IF NOT EXISTS steam_appid INTEGER;

CREATE TABLE IF NOT EXISTS date_events (
  id TEXT PRIMARY KEY,
  month INTEGER NOT NULL,
  day INTEGER NOT NULL,
  game_id TEXT,
  title_es TEXT NOT NULL,
  desc_es TEXT NOT NULL,
  title_en TEXT NOT NULL,
  desc_en TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS news_items (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  summary TEXT NOT NULL,
  source TEXT NOT NULL,
  url TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT '#5B8DEF',
  initials TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reviews (
  id TEXT PRIMARY KEY,
  game_id TEXT NOT NULL,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating NUMERIC(3,1),
  text TEXT NOT NULL DEFAULT '',
  platforms TEXT NOT NULL DEFAULT '[]',
  updated_at TEXT NOT NULL,
  UNIQUE(game_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_reviews_game ON reviews(game_id);
CREATE INDEX IF NOT EXISTS idx_reviews_user ON reviews(user_id);

CREATE TABLE IF NOT EXISTS helpful_votes (
  review_id TEXT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (review_id, user_id)
);
-- value: 1 = «Me gusta» (los votos de «te sirvió» que ya había quedan así), -1 = «No me gusta». Cada persona tiene un solo voto por reseña.
ALTER TABLE helpful_votes ADD COLUMN IF NOT EXISTS value INTEGER NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS daily_progress (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  guesses TEXT NOT NULL DEFAULT '[]',
  solved INTEGER NOT NULL DEFAULT 0,
  failed INTEGER NOT NULL DEFAULT 0,
  roulette_spins INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, date)
);

CREATE TABLE IF NOT EXISTS game_covers (
  title_key TEXT PRIMARY KEY,
  image_url TEXT,
  fetched_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS characters (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  game_id TEXT,
  game_ids TEXT NOT NULL DEFAULT '[]',
  banner_url TEXT,
  banner_game_id TEXT,
  photo_url TEXT,
  description TEXT,
  categories TEXT NOT NULL DEFAULT '[]',
  added_by TEXT,
  created_at TEXT NOT NULL,
  hidden INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_characters_game ON characters(game_id);

CREATE TABLE IF NOT EXISTS character_reviews (
  id TEXT PRIMARY KEY,
  character_id TEXT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating NUMERIC(3,1),
  text TEXT NOT NULL DEFAULT '',
  updated_at TEXT NOT NULL,
  UNIQUE(character_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_character_reviews_character ON character_reviews(character_id);
CREATE INDEX IF NOT EXISTS idx_character_reviews_user ON character_reviews(user_id);

-- Notas con medio punto (7.5): en una base que ya existía las columnas eran INTEGER y aquí pasan a NUMERIC(3,1) (las notas enteras quedan igual: 8 -> 8.0).
-- En una base nueva ya nacen así y esto no hace nada. El servidor las lee como número (parseNumeric en server/db.js).
DO $$ BEGIN
  IF (SELECT data_type FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'reviews' AND column_name = 'rating') = 'integer' THEN
    ALTER TABLE reviews ALTER COLUMN rating TYPE NUMERIC(3,1);
  END IF;
  IF (SELECT data_type FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'character_reviews' AND column_name = 'rating') = 'integer' THEN
    ALTER TABLE character_reviews ALTER COLUMN rating TYPE NUMERIC(3,1);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS game_suggestions (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  platforms TEXT NOT NULL DEFAULT '[]',
  genre TEXT,
  release_year INTEGER,
  note TEXT,
  submitted_by TEXT,
  status TEXT NOT NULL DEFAULT 'unread',
  created_at TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'game',
  related_game TEXT,
  categories TEXT NOT NULL DEFAULT '[]'
);

-- Contadores del límite de intentos (server/rateLimit.js). reset_at está en milisegundos desde epoch.
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  reset_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rate_limits_reset ON rate_limits(reset_at);

-- Reseñas ocultas por un admin: no se ven en el sitio (solo su autor las sigue viendo, con un aviso).
ALTER TABLE reviews ADD COLUMN IF NOT EXISTS hidden INTEGER NOT NULL DEFAULT 0;
ALTER TABLE character_reviews ADD COLUMN IF NOT EXISTS hidden INTEGER NOT NULL DEFAULT 0;
